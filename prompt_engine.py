def detect_role(question: str, ui_role: str | None = None) -> str:
    """Определить профессию по тексту запроса.

    ui_role — роль, которую владелец выбрал в интерфейсе (если выбрал). Она
    служит подсказкой при неоднозначности, но живой текст запроса важнее:
    человек написал «сделай рекламу» — отвечает маркетолог, даже если открыт
    экран «ассистента».
    """
    q = (question or "").lower()
    scores: dict[str, int] = {}
    for role, signals in _SIGNALS.items():
        s = sum(1 for sig in signals if sig in q)
        if s:
            scores[role] = s

    if scores:
        top = max(scores.values())
        winners = [r for r, s in scores.items() if s == top]
        if len(winners) == 1:
            return winners[0]
        # ничья: если интерфейсная роль среди победителей — берём её
        if ui_role in winners:
            return ui_role
        return winners[0]

    # сигналов нет: доверяем интерфейсной роли, иначе — руководитель
    if ui_role in PROFESSIONS:
        return ui_role
    return DEFAULT_ROLE


# Старые ключи ролей интерфейса → новые профессии (обратная совместимость с
# _ROLE_PERSONA в ai.py: assistant/sales/marketing/analyst/admin).
_LEGACY_ROLE_MAP = {
    "assistant": "executive",
    "sales": "sales",
    "marketing": "marketing",
    "analyst": "finance",
    "admin": "executive",
}


def normalize_ui_role(role: str | None) -> str | None:
    if not role:
        return None
    return _LEGACY_ROLE_MAP.get(role, role if role in PROFESSIONS else None)


