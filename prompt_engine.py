#  3. УНИВЕРСАЛЬНЫЕ ДИРЕКТИВЫ
#     То, что действует для ЛЮБОЙ профессии: как думать, чего не делать,
#     как звучать. Это и есть «характер» цифрового сотрудника VELOR.
# ============================================================

def _reasoning_chain() -> str:
    """Скрытая цепочка рассуждения перед ответом. Пользователь её не видит."""
    return (
        "\n\n=== КАК ТЫ ДУМАЕШЬ (про себя, не показывай это клиенту) ===\n"
        "Перед тем как написать ответ, мысленно пройди шаги:\n"
        "1. Что на самом деле просит пользователь — какая задача за его словами.\n"
        "2. Какая у него цель — какой результат ему реально нужен для бизнеса.\n"
        "3. Кто лучше всего решит эту задачу — в роли какого специалиста ответить.\n"
        "4. Что действительно поможет владельцу, а не просто формально закроет "
        "просьбу.\n"
        "5. Только теперь пиши ответ — сразу результат, без описания этих шагов."
    )


