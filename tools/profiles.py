def from_model(request):
    """Профиль под незнакомую отрасль. Нет модели или мусор в ответе — None."""
    try:
        import ai
        raw = ai._ask("Ты отвечаешь строго одним объектом JSON.",
                      [{"role": "user", "content": _ASK % str(request)[:80]}],
                      max_tokens=1200)
    except Exception:
        return None
    text = (raw or "").strip()
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        return None
    try:
        return _valid(json.loads(m.group(0)))
    except (ValueError, TypeError):
        return None


def profile_for(request):
    """Каталог → модель → общий профиль. Пустым не возвращается никогда."""
    got = from_catalog(request) or from_model(request)
    if not got:
        got = dict(GENERIC)
        # Слова владельца сохраняем в описании: пусть на экране будет то, что
        # он просил, даже когда точного профиля у нас нет.
        asked = re.sub(r"\s+", " ", str(request or "").strip())[:60]
        if asked:
            got["about"] = asked[0].upper() + asked[1:] + ". " + got["about"]
    full = dict(DEFAULTS)
    full.update(got)
    return full


