def payees(profile):
    """
    Кому платит этот бизнес: имя на каждую статью плюс двое на закупку.

    Возвращает словарь «статья → кому», а также main/spare/other. Незнакомую
    статью подписываем нейтрально: выдумывать название под каждую значило бы
    придумывать компании, которых нет.
    """
    out = {"other": "Прочие расходы"}
    for cat, _w in profile.get("expenses") or []:
        low = str(cat).lower()
        out[cat] = next((name for word, name in _PAYEE_BY_WORD if word in low),
                        "Прочие расходы")
    main, spare = _SUPPLIERS.get(profile.get("kind")) or ("Основной поставщик",
                                                          "Второй поставщик")
    out["main"], out["spare"] = main, spare
    return out


