def _norm(text):
    return " " + re.sub(r"\s+", " ", (text or "").strip().lower()) + " "


def from_catalog(request):
    """Готовый профиль по словам запроса. Ничего не подошло — None."""
    low = _norm(request)
    for p in CATALOG:
        if any(word in low for word in p["match"]):
            return dict(p)
    return None


def _valid(raw):
    """
    Профиль от модели годится, только если на нём соберётся связный набор.

    Проверяем не «похоже на правду», а ровно то, от чего зависит механика:
    услуг хватает, цены — целые числа, дешёвая и дорогая различаются в разы.
    Без последнего «потеряли шесть возможностей по цене» перестаёт что-либо
    значить: терять было нечего.
    """
    if not isinstance(raw, dict):
        return None
    svc = []
    for row in (raw.get("services") or [])[:8]:
        try:
            name = str(row["name"]).strip()[:60]
            price = int(row["price"])
            desc = str(row.get("desc") or "").strip()[:120] or "Стандартный объём работ."
        except (KeyError, TypeError, ValueError):
            continue
        if name and 100 <= price <= 5000000:
            svc.append((name, price, desc))
    if len(svc) < 5:
        return None
    prices = sorted(s[1] for s in svc)
    if prices[-1] < prices[0] * 4:
        return None

    title = str(raw.get("title") or "").strip()[:60]
    if not title:
        return None
    out = dict(GENERIC)
    out.update({
        "kind": re.sub(r"[^a-z0-9]+", "-", str(raw.get("kind") or "custom").lower())[:24] or "custom",
        "title": title,
        "about": str(raw.get("about") or GENERIC["about"]).strip()[:200],
        "ai_name": str(raw.get("ai_name") or title.split()[0]).strip()[:30],
        "greeting": str(raw.get("greeting") or GENERIC["greeting"]).strip()[:200],
        "services": svc,
        "source": "придумано моделью",
    })
    if raw.get("income_category"):
        out["income_category"] = str(raw["income_category"]).strip()[:30]
    if str(raw.get("clients_are") or "").startswith("комп"):
        out["clients"] = COMPANIES
    # Расходы от модели берём только названиями и долями. Рубли она называть
    # не должна: суммы механика считает от выручки, и подставленное число
    # немедленно вернуло бы демо в убыток, из которого мы его и вытаскивали.
    exp = []
    for row in (raw.get("expenses") or [])[:5]:
        try:
            exp.append((str(row["category"]).strip()[:30], max(1, int(row["share"]))))
        except (KeyError, TypeError, ValueError):
            continue
    if len(exp) >= 3:
        out["expenses"] = exp
    grow = str(raw.get("growing") or "").strip()[:30]
    if grow:
        out["growing"] = grow
    return out


