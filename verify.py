# -*- coding: utf-8 -*-
"""
Проверка ответа на выдумку — для кабинета владельца.

В канале продаж такая проверка есть давно (`sales.unproven`): там ответ,
который не подтверждается памятью бизнеса, просто НЕ уходит клиенту. Владельцу
эта модель не годится. Он задал вопрос — и молчание вместо ответа не защищает
его ни от чего, а только оставляет без ответа.

Поэтому здесь другой договор: ответ владелец получает всегда, но каждая цифра
в нём помечена — нашлась она в его данных или нет. Один раз модели дают шанс
исправиться (ей называют ровно те цифры, которых в данных нет), и если что-то
осталось непроверенным, об этом сказано прямо под ответом.

Что считаем подтверждением. Только то, что модель РЕАЛЬНО ВИДЕЛА: системный
промпт целиком плюс сам вопрос владельца. Всё, чего там не было, модель взять
неоткуда — значит, придумала.

Округление разрешено, и это не поблажка. «1,3 млн» про 1 318 400 ₽ — не
выдумка, а нормальная человеческая речь. Считаем цифру подтверждённой, если
настоящее число попадает в тот промежуток, который эта запись и означает:
«1,3 млн» покрывает от 1,25 до 1,35 млн, «31%» — от 30,5 до 31,5, а
«407 400 ₽» не покрывает ничего, кроме себя.

Был соблазн сделать границу вдвое шире: ложное обвинение во лжи дороже
пропущенного округления, и проверку, которая придирается, владелец выключит на
второй день. Но широкая граница подтверждала «12 клиентов» настоящими
одиннадцатью — счёт и деньги такой доброты не переживают. Оставлено ровно то,
что запись и означает.

Чего этот модуль НЕ делает и делать не должен:
  • не проверяет вывод и логику — только факты, которые можно сверить;
  • не считает сам и не выводит числа одно из другого. Разрешить «любое число,
    которое получается из двух известных» значило бы подтвердить почти всё:
    на двух сотнях чисел в промпте пара для нужного результата найдётся почти
    всегда, и проверка перестала бы что-либо означать;
  • ничего не блокирует — решение остаётся за владельцем.
"""
from __future__ import annotations

import re

# Пробелы, которыми разделяют разряды: обычный, неразрывный и узкий неразрывный.
_SP = "   "

# Число: либо с разделителями разрядов ровно по три цифры, либо просто число.
# Три цифры — не придирка: без этого «10 20» в таблице склеилось бы в 1020.
_NUMBER = (r"\d{1,3}(?:[" + _SP + r"]\d{3})+(?:[.,]\d+)?"
           r"|\d+(?:[.,]\d+)?")

_SCALES = (
    (re.compile(r"^(?:тыс\.?|тысяч\w*)$", re.I), 1000),
    (re.compile(r"^(?:млн\.?|миллион\w*)$", re.I), 1000000),
    (re.compile(r"^(?:млрд\.?|миллиард\w*)$", re.I), 1000000000),
)

# Единицы, по которым узнаём утверждение о факте. Года и лет здесь намеренно
# нет: «в 2026 году» — это дата, а не заявление о бизнесе, и ловить её значило
# бы подозревать модель в каждом предложении.
_UNITS = (
    ("сумма", r"₽|руб\w*|р\."),
    ("процент", r"%|процент\w*|п\.\s*п\."),
    ("срок", r"дн\w*|сут\w*|недел\w*|час\w*|минут\w*|месяц\w*"),
    ("количество", (r"клиент\w*|пациент\w*|заказ\w*|заявк\w*|лид\w*|сделк\w*|"
                    r"сотрудник\w*|визит\w*|товар\w*|позиц\w*|обращен\w*")),
)

# Между числом и единицей почти всегда что-то стоит: «47 новых клиентов»,
# «200 000 лишних рублей», «11 постоянных пациентов». Без этого зазора
# проверка пропускала ровно те утверждения, ради которых её и писали.
# Два слова — не больше: на трёх зазор начинает склеивать соседние мысли.
_GAP = r"(?:[" + _SP + r"]+[а-яёa-z]+){0,2}[" + _SP + r"]*"

_CLAIM = re.compile(
    r"(?P<num>" + _NUMBER + r")"
    r"[" + _SP + r"]*(?P<scale>тыс\.?|тысяч\w*|млн\.?|миллион\w*|млрд\.?|миллиард\w*)?"
    + _GAP +
    r"(?P<unit>" + "|".join(p for _, p in _UNITS) + r")",
    re.I)

_NUMBER_RE = re.compile(_NUMBER)

# Выдуманный клиент — вторая по цене выдумка после выдуманной суммы: владелец
# пойдёт звонить человеку, которого у него нет. Ловим слова с большой буквы
# внутри предложения — в русском тексте это почти всегда имя собственное.
#
# Два условия дались не сразу, и оба нашлись на первом же примере.
# Первое — падежи: «Марине Векшиной» не встречается в данных буквально, хотя
# клиентка Марина Векшина там есть. Поэтому сравниваем по началу слова:
# падеж живёт в конце, корень — в начале.
# Второе — начало предложения. «Позвоните Ивану Петрову» с проверкой «два
# слова с большой буквы» превращалось в претензию к «Позвоните Ивану»: первое
# слово предложения тоже с большой буквы. Поэтому первое слово каждого
# предложения не рассматриваем вовсе — и в ответ уходит «Ивану Петрову», то
# есть ровно то, что владельцу и надо увидеть.
_WORD = re.compile(r"[А-Яа-яЁё]{3,}")
_CAP = re.compile(r"[А-ЯЁ][а-яё]{2,}")
_HAS_LETTER = re.compile(r"[А-Яа-яЁёA-Za-z]")
_TRIM = "«»\"'(),;:—–- \t"


def _stem(word: str) -> str:
    """Начало слова без хвоста: падеж живёт в конце, корень — в начале."""
    return (word or "").lower()[:4]


def _unknown_names(answer: str, stems: set) -> list[str]:
    """Незнакомые имена собственные — подряд идущими кусками."""
    out = []
    for sentence in re.split(r"[.!?\n]+", answer or ""):
        words = [w.strip(_TRIM) for w in sentence.split()]
        words = [w for w in words if w and _HAS_LETTER.search(w)]
        run = []
        for i, w in enumerate(words):
            if i and _CAP.fullmatch(w) and _stem(w) not in stems:
                run.append(w)
                continue
            if run:
                out.append(" ".join(run))
                run = []
        if run:
            out.append(" ".join(run))
    return out


def _digits(raw: str) -> str:
    return re.sub("[" + _SP + "]", "", raw or "").replace(",", ".")


def _value_and_step(raw: str, scale: float = 1.0):
    """Число и цена деления, с которой оно написано.

    «1,3» написано с точностью до десятых — значит, за ним может стоять что
    угодно от 1,2 до 1,4. «407 400» написано до единиц — значит, ровно оно.
    """
    s = _digits(raw)
    try:
        value = float(s)
    except ValueError:
        return None, None
    step = 10.0 ** -len(s.split(".")[1]) if "." in s else 1.0
    return value * scale, step * scale


def _scale_of(word: str) -> float:
    for rx, mult in _SCALES:
        if word and rx.match(word.strip()):
            return float(mult)
    return 1.0


def _kind_of(unit: str) -> str:
    for name, pattern in _UNITS:
        if re.fullmatch(pattern, unit or "", re.I):
            return name
    return "число"


def known_numbers(grounding: str) -> list[float]:
    """Все числа, которые модель видела своими глазами."""
    out = []
    for m in _NUMBER_RE.finditer(grounding or ""):
        try:
            out.append(float(_digits(m.group(0))))
        except ValueError:
            continue
    return out


def check(answer: str, grounding: str) -> list[dict]:
    """
    Что в ответе не подтверждается данными. Пустой список — всё сверено.

    Возвращаем не только текст промаха, но и сам фрагмент: по нему владелец
    находит место в ответе, а модель — что именно переписать.
    """
    known = known_numbers(grounding)
    ground = grounding or ""
    problems, seen = [], set()

    for m in _CLAIM.finditer(answer or ""):
        scale = _scale_of(m.group("scale") or "")
        value, step = _value_and_step(m.group("num"), scale)
        if value is None:
            continue
        # Половина последнего написанного разряда — ровно то, что означает
        # «округлено до этой точности». Целая единица казалась добрее, но она
        # подтверждала «12 клиентов» настоящими одиннадцатью: счёт и деньги
        # такой доброты не переживают.
        if any(abs(g - value) <= step / 2 + 1e-9 for g in known):
            continue
        text = " ".join(m.group(0).split())
        if text in seen:
            continue
        seen.add(text)
        problems.append({"text": text, "kind": _kind_of(m.group("unit")),
                         "why": "нет в ваших данных"})

    stems = {_stem(w) for w in _WORD.findall(ground)}
    for name in _unknown_names(answer or "", stems):
        if name in seen:
            continue
        seen.add(name)
        problems.append({"text": name, "kind": "имя",
                         "why": "нет в ваших данных"})

    return problems


# ── как об этом сказать ────────────────────────────────────────────────────

def note(problems: list[dict], *, creative: bool = False) -> str:
    """Строка под ответом. Она же — обещание продукта, поэтому пишем её честно
    и в обе стороны: и когда всё сошлось, и когда нет."""
    if not problems:
        return "Все цифры в ответе сверены с вашими данными."
    what = ", ".join("«%s»" % p["text"] for p in problems[:5])
    tail = " и ещё %d" % (len(problems) - 5) if len(problems) > 5 else ""
    if creative:
        return ("Это придуманный текст: " + what + tail
                + " — не из ваших данных. Проверьте перед публикацией.")
    return ("Не нашлось в ваших данных: " + what + tail
            + ". Остальное сверено. Проверьте эти места сами.")


def repair_system(problems: list[dict]) -> str:
    """Один шанс исправиться. Формулировка важна: «замени на правильное» —
    приглашение придумать другое число, поэтому разрешаем ровно два выхода —
    взять число из данных или убрать утверждение целиком."""
    what = ", ".join("«%s»" % p["text"] for p in problems[:8])
    return (
        "Ты — редактор-факт-чекер VELOR. В тексте ниже есть данные, которых НЕТ "
        "в материалах компании: " + what + ". С каждым таким местом сделай "
        "ровно одно из двух: либо поставь настоящее число из материалов, либо "
        "убери утверждение вместе с цифрой. Придумывать новые числа, "
        "усреднять и прикидывать «примерно» — нельзя. Всё остальное в тексте "
        "оставь как есть, слово в слово. Верни только исправленный текст."
    )
