# -*- coding: utf-8 -*-
"""
Проверка фактов в кабинете владельца — защита от выдумок модели.

В канале продаж непроверенный ответ просто не уходит клиенту. Владельцу такое
не годится: он задал вопрос, и молчание не защищает его ни от чего. Договор
здесь другой — ответ приходит всегда, но каждая цифра помечена: нашлась она в
данных или нет, и один раз модели дают шанс исправиться.

Что проверяем:
  1) разбор утверждений — суммы, проценты, сроки, счёт, имена;
  2) округление разрешено ровно настолько, насколько означает сама запись:
     «1,3 млн» покрывает 1 318 400, но «12 клиентов» не покрывают одиннадцати;
  3) что НЕ должно считаться претензией: «в 2 раза», даты, знакомые имена
     в любом падеже, слово в начале предложения с большой буквы;
  4) весь путь ответа: выдумка ловится, модели даётся один шанс, вердикт
     доезжает до экрана;
  5) правка принимается, только если она помогла, и не принимается, если
     модель вместо исправления вычеркнула ответ;
  6) творческим ролям ответ не переписывают — придуманная акция и должна быть
     придуманной, — но о том, что цифра не из данных, всё равно говорят;
  7) клиентский путь проверкой не трогается: это горячий вебхук.
"""
import os, sys, tempfile, pathlib

TMP = pathlib.Path(tempfile.mkdtemp())
os.environ["DB_PATH"] = str(TMP / "t.db")
os.environ["LOG_DIR"] = str(TMP)
os.environ["UPLOAD_DIR"] = str(TMP / "uploads")
os.environ["APP_ENV"] = "development"
os.environ["OWNER_LOGIN"] = "testowner"
os.environ["OWNER_PASSWORD"] = "s3cret-owner"
os.environ["JWT_SECRET"] = "test-secret-verify"
os.environ["SECRET_KEY"] = "test-box-key"
os.environ["DATABASE_URL"] = ""
os.environ["GEMINI_API_KEY"] = ""
os.environ["GIGACHAT_AUTH_KEY"] = ""
os.environ["ANTHROPIC_API_KEY"] = ""
os.environ["DISABLE_SYNC_WORKER"] = "1"
sys.stdout.reconfigure(encoding="utf-8")
ROOT = str(pathlib.Path(__file__).resolve().parents[1])
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))
os.chdir(ROOT)

from fastapi.testclient import TestClient                            # noqa: E402
import server, database, context_engine, verify, ai                  # noqa: E402
import demo_business                                                 # noqa: E402

ok = fail = 0


def check(name, cond, extra=""):
    global ok, fail
    if cond:
        ok += 1; print("  OK  ", name)
    else:
        fail += 1; print("  FAIL", name, extra)


database.init_db()
bid = demo_business.build("verify-clinic", "verify-pass-1")["business_id"]

GROUND = """Показатели за 30 дн.:
  Выручка: 1 318 400 ₽ · -7% к прошлому периоду
  Расходы: 911 000 ₽ · +5%
  Прибыль: 407 400 ₽ · -26%
  Маржа: 30.9%
  Новые клиенты: 11
  3 горячих клиента ждут ответа. Дольше всех ждёт 43 часа.
  5 клиентов не возвращались больше 30 дней, принесли 156 900 ₽.
  Например: Марина Векшина, Алиса Ветрова, Регина Ахметова."""


def n(text):
    return len(verify.check(text, GROUND))


print("== ЧТО СЧИТАЕТСЯ ПОДТВЕРЖДЁННЫМ ==")
check("точные цифры проходят", n("Прибыль 407 400 ₽ при выручке 1 318 400 ₽.") == 0)
check("округление «1,3 млн» покрывает 1 318 400", n("Выручка около 1,3 млн ₽.") == 0)
check("округление «31%» покрывает 30.9", n("Маржа 31%.") == 0)
check("рубли словом тоже сверяются", n("Прибыль 407 400 рублей.") == 0)
check("проценты словом тоже", n("Маржа 30.9 процента.") == 0)
check("счёт из данных проходит", n("У вас 11 новых клиентов.") == 0)
check("срок из данных проходит", n("Дольше всех ждёт 43 часа.") == 0)

print("\n== ЧТО ЛОВИТСЯ ==")
check("выдуманная сумма", n("Реклама съела 200 000 ₽.") == 1)
check("выдуманный процент", n("Конверсия выросла на 22%.") == 1)
check("выдуманный срок", n("Ответьте в течение 72 часов.") == 1)
check("выдуманный счёт", n("У вас 47 новых клиентов.") == 1)
check("счёт мимо всего на единицу — тоже выдумка",
      n("У вас 12 новых клиентов.") == 1,
      "щедрый допуск подтверждал бы 12 одиннадцатью")
check("слишком смелое округление", n("Выручка 1,5 млн ₽.") == 1)
check("несколько промахов — несколько строк",
      n("Реклама съела 200 000 ₽ — это 22% расходов.") == 2)

print("\n== ЧЕГО НЕЛЬЗЯ ОБЪЯВЛЯТЬ ВЫДУМКОЙ ==")
# Ложное обвинение убивает такую проверку вернее, чем пропуск: владелец
# перестанет её читать на второй день.
check("«в 2 раза» — не утверждение о цифре", n("Прибыль упала в 2 раза.") == 0)
check("текст без цифр чист", n("Прибыль упала. Расходы выросли.") == 0)
check("два числа подряд не склеиваются", n("Всего 5 из 11 клиентов вернулись.") == 0)

print("\n== ИМЕНА ==")
check("знакомое имя в другом падеже — не выдумка",
      n("Позвоните Марине Векшиной — она давно не была.") == 0,
      "падеж не должен превращать клиента в выдумку")
check("выдуманный человек пойман",
      n("Позвоните Ивану Петрову — он давно не был.") == 1)
check("и назван именно он, а не глагол перед ним",
      [p["text"] for p in verify.check("Позвоните Ивану Петрову.", GROUND)] == ["Ивану Петрову"],
      verify.check("Позвоните Ивану Петрову.", GROUND))
check("имя в начале предложения тоже ловится",
      n("Иван Петров давно не был у вас.") == 1)
check("несколько знакомых имён подряд проходят",
      n("Свяжитесь с Алисой Ветровой и Региной Ахметовой.") == 0)

print("\n== ВЕСЬ ПУТЬ ОТВЕТА ==")
# Модель подменяем: без ключей её всё равно нет, а проверять надо поведение
# вокруг неё — что ловится, что переписывается, что доезжает до экрана.
CALLS = []
_real_ask = ai._ask


def fake(script):
    """script — список ответов подряд; последний повторяется."""
    box = list(script)

    def _ask(system, messages, **kw):
        CALLS.append(system)
        return box.pop(0) if len(box) > 1 else box[0]
    return _ask


b = database.get_business(bid)

ai._ask = fake(["Прибыль упала. Виновата реклама: 250 000 ₽ за месяц."])
CALLS.clear()
got = context_engine.respond_verified(bid, "Почему прибыль упала?")
check("выдумка в ответе поймана", bool(got["unverified"]), got)
check("и названа в вердикте", "250 000 ₽" in got["note"], got["note"])
check("ответ всё равно отдан", bool(got["answer"]), got)

# Модель исправляется со второго раза — правку принимаем.
# Исправленный вариант намеренно БЕЗ цифр: правку принимаем за то, что она
# убрала выдумку, а не за то, что подставила другое число. Числа демо-клиники
# двигаются вместе с датой, и тест на них ломался бы каждый день.
ai._ask = fake(["Прибыль упала. Виновата реклама: 250 000 ₽ за месяц.",
                "Прибыль упала из-за роста расходов. Разберите статьи расходов."])
CALLS.clear()
got = context_engine.respond_verified(bid, "Почему прибыль упала?")
check("правка принята, когда помогла", got["repaired"] is True, got)
check("и вердикт стал чистым", not got["unverified"], got)
check("в чистом случае так и сказано", "сверены" in got["note"], got["note"])
check("на исправление ушёл ровно один лишний запрос", len(CALLS) == 2, len(CALLS))

# Модель «исправила» ответ, вычеркнув его. Такую правку не берём.
ai._ask = fake(["Прибыль упала. Виновата реклама: 250 000 ₽ за месяц. "
                "Стоит разобрать статьи расходов за два периода.", "Ок."])
got = context_engine.respond_verified(bid, "Почему прибыль упала?")
check("правка-обрубок отклонена", "250 000" in got["answer"], got["answer"])
check("и вердикт остался честным", bool(got["unverified"]), got)

# Правка нормальной длины, но с ДВУМЯ выдумками вместо одной. Длина её
# пропускает — отклонить такую может только сравнение «стало ли лучше».
ai._ask = fake(["Прибыль упала. Виновата реклама: 250 000 ₽ за месяц.",
                "Прибыль упала. Виновата реклама: 250 000 ₽, и ещё аренда "
                "333 111 ₽ за тот же месяц."])
got = context_engine.respond_verified(bid, "Почему прибыль упала?")
check("правка, которая сделала хуже, отклонена", got["repaired"] is False, got)
check("и в ответе осталась одна выдумка, а не две",
      len(got["unverified"]) == 1, got["unverified"])

# Творческой роли ответ не переписываем.
ai._ask = fake(["Акция выходного дня: скидка 15% на чистку, дарим 500 ₽ на следующий визит."])
CALLS.clear()
got = context_engine.respond_verified(bid, "Придумай акцию на выходные")
check("творческий ответ не переписан", len(CALLS) == 1, len(CALLS))
check("но о выдуманных цифрах сказано", bool(got["unverified"]), got)
check("и сказано по-другому — это придуманный текст",
      "придуманный" in got["note"], got["note"])

print("\n== ВЕРДИКТ ДОЕЗЖАЕТ ДО ЭКРАНА ==")
ai._ask = fake(["Прибыль упала. Виновата реклама: 250 000 ₽ за месяц.", "Ок."])
# Ключей в тестовой среде нет, и сервер честно отказывается идти к модели ещё
# до кабинета. Подменяем и этот ответ: проверяем дорогу вердикта до экрана, а
# не наличие ключа.
_real_avail = ai.ai_available
ai.ai_available = lambda *a, **k: True
c = TestClient(server.app)
tok = c.post("/api/business-login", json={"login": "verify-clinic",
                                          "password": "verify-pass-1"}).json()["token"]
r = c.post("/api/ask", headers={"X-Auth": tok},
           json={"question": "Почему прибыль упала?", "role": "assistant"})
d = r.json()
check("ответ отдан", d.get("ok") and d.get("answer"), d)
check("вердикт есть в ответе API", bool(d.get("check")), d)
check("и список непроверенного тоже", isinstance(d.get("unverified"), list), d)

page = open("web/home.html", encoding="utf-8").read()
check("экран показывает вердикт", "data.check" in page)
check("и текстом, а не разметкой", "v.textContent = data.check" in page)
check("состояние сказано словом, а не одним цветом",
      ".checked.warn::before" in page and "content:'!'" in page)

ai.ai_available = _real_avail

print("\n== КЛИЕНТСКИЙ ПУТЬ НЕ ТРОНУТ ==")
# Горячий вебхук отвечает клиенту в реальном времени. Лишний проход модели
# ради проверки, которую клиент всё равно не увидит, здесь недопустим.
ai._ask = fake(["Здравствуйте! Имплант под ключ — 78 000 ₽."])
CALLS.clear()
reply, order = context_engine.respond_chat(bid, [{"role": "user", "content": "Сколько имплант?"}])
check("клиенту отвечаем одним запросом", len(CALLS) == 1, len(CALLS))
check("и ответ уходит как есть", bool(reply), reply)

ai._ask = _real_ask

print("\nИТОГО: успешно %d, провалено %d" % (ok, fail))
sys.exit(1 if fail else 0)
